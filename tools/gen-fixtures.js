// Turns tools/corpus.jsonl (harvested from the reference test suite by
// tools/harvest.js) into MoonBit differential tests.
//
//   node tools/gen-fixtures.js
//
// Writes:
//   parser/meta_fixture_test.mbt     grammar parser: AST or syntax error
//   compiler/pass_fixture_test.mbt   individual compiler passes
//   fixtures/generate_fixture_test.mbt  generate + parse (see its header)
"use strict";
const fs = require("fs");
const path = require("path");
const { mbtString } = require("./gen-program");

const root = path.join(__dirname, "..");
const corpus = fs.readFileSync(path.join(__dirname, "corpus.jsonl"), "utf8")
  .trim().split("\n").map(JSON.parse);

// Replaces lone surrogates (which MoonBit's JSON parser rejects) with a
// marker; the MoonBit side normalizes actual values the same way.
function normalizeString(s) {
  let out = "";
  for (let i = 0; i < s.length; i++) {
    const c = s.charCodeAt(i);
    if (c >= 0xd800 && c <= 0xdbff) {
      const d = s.charCodeAt(i + 1);
      if (d >= 0xdc00 && d <= 0xdfff) { out += s[i] + s[i + 1]; i++; continue; }
      out += "<lone:" + c.toString(16) + ">";
    } else if (c >= 0xdc00 && c <= 0xdfff) {
      out += "<lone:" + c.toString(16) + ">";
    } else out += s[i];
  }
  return out;
}
function normalize(v) {
  if (typeof v === "string") return normalizeString(v);
  if (Array.isArray(v)) return v.map(normalize);
  if (v && typeof v === "object") {
    const r = {};
    for (const k of Object.keys(v)) if (v[k] !== undefined) r[normalizeString(k)] = normalize(v[k]);
    return r;
  }
  return v;
}
function jsonLit(v) {
  return mbtString(JSON.stringify(normalize(v)));
}
function unique(records, key) {
  const seen = new Map();
  for (const r of records) {
    const k = key(r);
    if (!seen.has(k)) seen.set(k, r);
  }
  return [...seen.values()];
}
function errorJson(e) {
  const r = { name: e.name, message: e.message };
  if (e.location !== undefined) r.location = e.location;
  if (e.expected !== undefined) r.expected = e.expected;
  if (e.found !== undefined) r.found = e.found;
  return r;
}
function header(what) {
  return "// Code generated by tools/gen-fixtures.js from tools/corpus.jsonl. DO NOT EDIT.\n" +
    "// " + what + "\n";
}

// ---- grammar parser -------------------------------------------------------
{
  const metas = unique(corpus.filter(r => r.kind === "meta"),
    r => JSON.stringify([r.input, r.options]));
  const out = [header("Differential tests of the grammar parser against PEG.js.")];
  out.push("///|", "let meta_cases : Array[(String, Bool, String)] = [");
  for (const r of metas) {
    const opts = r.options && typeof r.options === "object" && !("$" in r.options) ? r.options : {};
    const expected = r.ok ? { ok: r.result } : { error: errorJson(r.error) };
    out.push("  (" + mbtString(r.input) + ", " + !!opts.extractComments + ", " + jsonLit(expected) + "),");
  }
  out.push("]", "");
  out.push(`///|
test "grammar parser matches PEG.js" {
  let mut failures = 0
  for i, c in meta_cases {
    let (input, extract_comments, expected_text) = c
    let expected = @json.parse(expected_text)
    let actual : Json = try @parser.parse(input, extract_comments~) catch {
      @runtime.SyntaxError(_) as e => { "error": e.to_json() }
      e => { "error": { "name": "unexpected", "message": "\\{e}" } }
    } noraise {
      g => { "ok": g.to_json() }
    }
    let actual = @fixture.normalize(actual)
    if actual != expected {
      failures += 1
      if failures <= 5 {
        println("case \\{i} differs: \\{input}")
        println("  expected: \\{expected.stringify()}")
        println("  actual:   \\{actual.stringify()}")
      }
    }
  }
  assert_eq(failures, 0)
}
`);
  fs.writeFileSync(path.join(root, "parser", "meta_fixture_test.mbt"), out.join("\n"));
  console.log("meta cases:", metas.length);
}
